create table if not exists provider_subscriptions (
    id bigint generated by default as identity primary key,
    scope_type varchar(30) not null,
    scope_id bigint not null,
    plan_id bigint not null,
    billing_period varchar(20) not null,
    status varchar(30) not null,
    room_limit integer not null,
    employee_limit integer not null,
    starts_at timestamp,
    expires_at timestamp,
    grace_ends_at timestamp,
    usage_grace_ends_at timestamp,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    constraint uk_provider_subscriptions_scope unique (scope_type, scope_id),
    constraint fk_provider_subscriptions_plan foreign key (plan_id) references subscription_plans (id),
    constraint chk_provider_subscriptions_scope check (scope_type in ('INDIVIDUAL_WORKSPACE', 'BUSINESS')),
    constraint chk_provider_subscriptions_period check (billing_period in ('MONTHLY', 'YEARLY')),
    constraint chk_provider_subscriptions_status check (
        status in ('PENDING_PAYMENT', 'ACTIVE', 'GRACE_PERIOD', 'SUSPENDED', 'CANCELLED')
    )
);

create index if not exists idx_provider_subscriptions_status_expiry
    on provider_subscriptions (status, expires_at, grace_ends_at);

