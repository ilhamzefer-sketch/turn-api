create table if not exists subscription_plans (
    id bigint generated by default as identity primary key,
    code varchar(60) not null unique,
    name varchar(120) not null,
    billing_period varchar(20) not null,
    amount bigint not null,
    currency varchar(3) not null,
    room_limit integer not null,
    employee_limit integer not null,
    active boolean not null default true,
    created_at timestamp not null default current_timestamp,
    constraint chk_subscription_plans_period check (billing_period in ('MONTHLY', 'YEARLY')),
    constraint chk_subscription_plans_amount check (amount > 0),
    constraint chk_subscription_plans_limits check (room_limit > 0 and employee_limit > 0)
);

