    claimant_name varchar(160) not null,
    claimant_contact_phone varchar(13) not null,
    description varchar(2000) not null,
    status varchar(30) not null,
    resolution_note varchar(2000),
    resolution_action varchar(30),
    reviewed_by_admin varchar(120),
    password_reset_required_at timestamp,
