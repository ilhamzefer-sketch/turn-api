create table if not exists service_ratings (
    id bigint generated by default as identity primary key,
    live_queue_entry_id bigint unique,
    planned_booking_id bigint unique,
    customer_user_id bigint not null,
    room_id bigint not null,
    score integer not null,
    comment varchar(1000),
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    editable_until timestamp not null,
    constraint fk_service_ratings_live_entry foreign key (live_queue_entry_id) references live_queue_entries (id),
    constraint fk_service_ratings_booking foreign key (planned_booking_id) references planned_bookings (id),
    constraint fk_service_ratings_customer foreign key (customer_user_id) references users (id),
    constraint fk_service_ratings_room foreign key (room_id) references rooms (id),
    constraint chk_service_ratings_target check (
        (live_queue_entry_id is not null and planned_booking_id is null)
        or (live_queue_entry_id is null and planned_booking_id is not null)
    ),
    constraint chk_service_ratings_score check (score between 1 and 5)
);

create index if not exists idx_service_ratings_room on service_ratings (room_id, created_at);

